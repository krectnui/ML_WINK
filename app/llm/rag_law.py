def calculate_simple_rating(category: str, level: int) -> str:
    """Простая логика рейтингов по категории и уровню"""
    rules = {
        'sexual': {1: '6+', 2: '12+', 3: '16+', 4: '18+'},
        'violence': {1: '6+', 2: '12+', 3: '16+', 4: '18+'}, 
        'profanity': {1: '6+', 2: '12+', 3: '16+', 4: '18+'},
        'drugs_alcohol': {1: '6+', 2: '12+', 3: '16+', 4: '18+'},
        'scary': {1: '6+', 2: '12+', 3: '16+', 4: '18+'}
    }
    return rules.get(category, {}).get(level, '6+')

def generate_recommendations(category: str, level: int, element_type: str = "action", character: str = "") -> str:
    """
    Генерирует рекомендации **на основе закона №436-ФЗ** — без LLM.
    Ответ всегда одинаковый для одного и того же типа нарушения.
    """
    # Основные рекомендации по категориям — строго по закону
    recs = {
        'profanity': (
            "Согласно п. 1 ст. 5 ФЗ-436, использование нецензурной лексики повышает возрастной рейтинг. "
            "Для снижения рейтинга рекомендуется заменить грубые выражения на нейтральные или убрать их."
        ),
        'violence': (
            "Согласно п. 2 ст. 5 ФЗ-436, детализированные сцены насилия требуют рейтинга 16+ или 18+. "
            "Для снижения рейтинга рекомендуется избегать прямых описаний: использовать намёки, звуки или косвенные формулировки."
        ),
        'drugs_alcohol': (
            "Согласно п. 3 ст. 5 ФЗ-436, демонстрация употребления наркотиков или алкоголя в положительном свете повышает рейтинг. "
            "Для снижения рейтинга рекомендуется убрать такие сцены или показать негативные последствия."
        ),
        'erotic': (
            "Согласно п. 4 ст. 5 ФЗ-436, эротические сцены с детализацией интимных действий требуют рейтинга 18+. "
            "Для снижения рейтинга рекомендуется заменить прямые описания на атмосферу, намёки или эмоциональные формулировки."
        ),
        'scary': (
            "Согласно п. 5 ст. 5 ФЗ-436, сцены, вызывающие страх у несовершеннолетних, требуют повышенного рейтинга. "
            "Для снижения рейтинга рекомендуется убрать жуткие детали (кровь, монстры, крики) и использовать таинственность вместо пугающего."
        ),
    }

    # Если категория неизвестна — универсальная рекомендация
    if category not in recs:
        return (
            "Рекомендуется смягчить сцену, исключив элементы, которые могут быть расценены как насилие, "
            "ненормативная лексика, эротика, употребление наркотиков/алкоголя или пугающие сцены, "
            "согласно Федеральному закону №436-ФЗ."
        )

    rec = recs[category]

    # Добавляем примечание, если это реплика персонажа
    if element_type == "dialogue" and character:
        rec += f"\n\n(Примечание: рекомендация относится к реплике персонажа «{character}».)"

    return rec